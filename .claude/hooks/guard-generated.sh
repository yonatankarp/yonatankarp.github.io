#!/usr/bin/env bash
# PreToolUse (Edit|Write): refuse hand edits to files a script writes, and name the script to rerun instead.
f=$(jq -r '.tool_input.file_path // empty')
rel=${f#"${CLAUDE_PROJECT_DIR:-$PWD}"/}

case "$rel" in
  static/building/pixel/*)           why="the art pipeline (web3d/pixel/gen_*.py; npm run art rebuilds it all)" ;;
  data/floor_accents.yaml)           why="web3d/pixel/gen_floors.py (from FLOORS; --data writes only this)" ;;
  data/timezones.json)               why="node scripts/gen-timezones.js" ;;
  assets/building/*)                 why="Vite (npm run build:building)" ;;
  assets/diagrams/*)                 why="node scripts/render-diagrams.js" ;;
  static/images/blog/covers/pixel/*) why="web3d/pixel/pixelate.py (paint_covers.py --install rebakes them all)" ;;
  static/images/blog/pixel/*)        why="web3d/pixel/paint_covers.py --install-inline" ;;
  *) exit 0 ;;
esac

echo "$rel is generated by $why. Change its source and rerun that, never the copy." >&2
exit 2
